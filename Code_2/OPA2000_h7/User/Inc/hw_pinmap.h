/**
 * @file    hw_pinmap.h
 * @brief   Hardware pin/port macros for OPA2000 H7 Control firmware
 *
 * @details This header centralises every GPIO pin, ADC channel rank, timer
 *          channel and external IRQ that the firmware touches.  All source
 *          files (Control / GUI / Networking) include this header rather
 *          than redefining the pinout locally.
 *
 *          Reference: OPA2000_h7.ioc + lceda Control schematic
 *          (U5 = STM32H7B0ZBT6 LQFP144).  Cross-checked against
 *          .trae/all_nets.json 2026-10.
 *
 *          ----------------------------------------------------------------
 *          引脚号的真相源是 CubeMX，不要在这里硬编码
 *          ----------------------------------------------------------------
 *          CubeMX 只为它自己配置的引脚生成宏，落在 Core/Inc/main.h。
 *          分工如下：
 *
 *            - 已由 ioc 生成的（GPIO 输出/输入，如 LPF1..6、RELAY1/2、
 *              PWR_ON、RF_BIAS、PSU、PTT_IN/OUT、BL_PWM …）：**真相源是
 *              main.h**。本文件里对应的 *_Pin / *_GPIO_Port 一律写成
 *              别名（`#define X_Pin  main.h 里的名字`），不重复写死数值。
 *              这样在 CubeMX 里改引脚后重新生成，固件自动跟随；编译器
 *              也会在名字对不上时直接报错，而不是静默操作错误的脚。
 *
 *            - CubeMX 不产生的（定时器通道、ADC rank、AWD 通道、EXTI
 *              中断号、DAC 通道、以及 LPUART1 / UART4 / I2C2 / USB /
 *              SDMMC2 / FDCAN1 / SPI6 这些外设引脚）：真相源是本文件。
 *              CubeMX 对这些外设不生成宏，固件只能自己声明。
 *
 *          历史上本文件把前者也硬编码了一遍，于是出现了"同名不同名"的
 *          两套宏（如 PWR_ON_Pin 与 PWR_ON_SIG_Pin）。两套宏名字不同，
 *          #ifndef 保护对它们无效，编译不报错，ioc 改了引脚也不会有人
 *          提醒 —— 那才是真正危险的地方。现在统一成别名。
 *
 *          DO NOT MODIFY without updating both ioc and the firmware
 *          design spec.  The MCU is U5 in the schematic (not U1).
 *
 * @version 1.0
 * @date    2026-10
 * @author  Control Agent (wt-control branch)
 */

