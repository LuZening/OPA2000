#define PTT_OUT_GPIO_Port  GPIOC
#define PTT_OUT_Pin        GPIO_PIN_15
#endif
#define PTT_OUT_ON()       HAL_GPIO_WritePin(PTT_OUT_GPIO_Port, PTT_OUT_Pin, GPIO_PIN_SET)
#define PTT_OUT_OFF()      HAL_GPIO_WritePin(PTT_OUT_GPIO_Port, PTT_OUT_Pin, GPIO_PIN_RESET)

