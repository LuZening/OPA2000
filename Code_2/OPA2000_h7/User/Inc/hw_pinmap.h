#define RF_BIAS_Pin        RF_BIAS_ON_Pin
#define RF_BIAS_ENABLE()   HAL_GPIO_WritePin(RF_BIAS_GPIO_Port, RF_BIAS_Pin, GPIO_PIN_SET)
#define RF_BIAS_DISABLE()  HAL_GPIO_WritePin(RF_BIAS_GPIO_Port, RF_BIAS_Pin, GPIO_PIN_RESET)

/* HARDPWR_ERR (PB12): EXTI12 rising edge, hardware fault from supply.
 * HARDPWR_ERR_GPIO_Port / HARDPWR_ERR_Pin come straight from main.h. */

/* RF_IN_PROTECT_CPU_SIG (PB13): fault output (push-pull, pull to high).
 * CubeMX calls it RF_IN_PROTECT_CPU_SIG; alias down to the short name. */
#define RF_IN_PROTECT_GPIO_Port  RF_IN_PROTECT_CPU_SIG_GPIO_Port
#define RF_IN_PROTECT_Pin        RF_IN_PROTECT_CPU_SIG_Pin
#define RF_IN_PROTECT_RAISE()   HAL_GPIO_WritePin(RF_IN_PROTECT_GPIO_Port, RF_IN_PROTECT_Pin, GPIO_PIN_SET)
#define RF_IN_PROTECT_CLEAR()   HAL_GPIO_WritePin(RF_IN_PROTECT_GPIO_Port, RF_IN_PROTECT_Pin, GPIO_PIN_RESET)

/* CLEAR_FAULTX_OC (PG1): GPIO output, open-drain (GPIO_MODE_OUTPUT_OD),
 * wired to C65-2 / D10-1 / R71-1.  Open-drain means the pin can only pull
 * the net down - it cannot drive it high.  So:
 *
 *   LOW  = the pin pulls the net low  -> the external fault latch is held
 *          in its cleared state and no latched alarm survives.
 *   HIGH = the output stage is released -> the net floats back to its
 *          pull-up and the latch works normally again.
 *
 * Written HIGH at the end of MX_GPIO_Init(), i.e. the reset state is
 * "normal operation"; boot then drives it LOW for the whole power-on
 * stabilisation window (see adc_stabilisation_tick() in user_adc.c) and
 * releases it only once the readings are trustworthy.
 *
 * CLEAR_FAULTX_OC_GPIO_Port / CLEAR_FAULTX_OC_Pin come straight from
 * main.h (PG1), so no alias is needed. */
#define CLEAR_FAULTX_OC_LOW()   HAL_GPIO_WritePin(CLEAR_FAULTX_OC_GPIO_Port, CLEAR_FAULTX_OC_Pin, GPIO_PIN_RESET)
#define CLEAR_FAULTX_OC_HIGH()  HAL_GPIO_WritePin(CLEAR_FAULTX_OC_GPIO_Port, CLEAR_FAULTX_OC_Pin, GPIO_PIN_SET)

/* CPU_READY (PD8): GPIO output (status indication).
 * CPU_READY_GPIO_Port / CPU_READY_Pin come straight from main.h. */

/* TFT_DISP (PE10): LTDC panel "display enable" line.  HIGH = the panel's
 * source driver and gate driver come out of standby and accept the LTDC
 * pixel stream.  LOW = blanked, no power wasted in the panel's row/col
 * drivers.  Driven HIGH only once the GUI has painted its first frame
 * (g_gui_ready), via boot_backlight_on() in boot.c.  Drawn LOW again on
 * power_soft_off() so the panel darkens in step with the supply.
 *
 * TFT_DISP_GPIO_Port / TFT_DISP_Pin come straight from main.h (PE10), same
 * as the other CubeMX-named pins above - no alias needed.
 *
 * Polarity assumption: HIGH enables.  This matches the ST RGB-LCD
 * reference design and most third-party panels with a "DISP" pin.  If
 * a particular panel uses active-low DISP, invert both macros. */
#define TFT_DISP_ENABLE()    HAL_GPIO_WritePin(TFT_DISP_GPIO_Port, TFT_DISP_Pin, GPIO_PIN_SET)
#define TFT_DISP_DISABLE()   HAL_GPIO_WritePin(TFT_DISP_GPIO_Port, TFT_DISP_Pin, GPIO_PIN_RESET)

/* LIGHTNING_PROTECTION_A / B (PB9 / PD9): GPIO outputs, jumper pads.
 * CubeMX names them LIGHTNING_PROTECTION_A / _B; alias down. */
#define LIGHTNING_A_GPIO_Port  LIGHTNING_PROTECTION_A_GPIO_Port
#define LIGHTNING_A_Pin        LIGHTNING_PROTECTION_A_Pin
#define LIGHTNING_B_GPIO_Port  LIGHTNING_PROTECTION_B_GPIO_Port
#define LIGHTNING_B_Pin        LIGHTNING_PROTECTION_B_Pin

