/* ===========================================================================
 *  2. LPF band switching (HIGH-ACTIVE, LPF1 .. LPF6)
 *
 *  The LPFn_Pin / LPFn_GPIO_Port macros are generated by CubeMX into
 *  Core/Inc/main.h and are therefore the single source of truth.  The
 *  #ifndef guards only supply them for the host unit-test build, where
 *  main.h is replaced by User/Tests/stubs/main.h.
 *
 *  ioc / main.h assignment:
 *      LPF1 = PE1  (R45  -> H3-2)
 *      LPF2 = PE2  (R50  -> H3-3)
 *      LPF3 = PE3  (R51  -> H3-4)
 *      LPF4 = PE4  (R61  -> H3-5)
 *      LPF5 = PE5  (R62  -> H3-6)
 *      LPF6 = PC14 (R105 -> H3-7)
 *
 *  Band -> LPF mapping (lower index == shorter wavelength):
 *      LPF1 = 15-10 m
 *      LPF2 = 20-17 m
 *      LPF3 = 40-30 m
 *      LPF4 = 80 m
 *      LPF5 = 160 m
 *      LPF6 = spare (only 5 combined bands exist)
 *
 *  The mapping itself lives in switch_band() (power_control.c).
 * ===========================================================================*/
#ifndef LPF1_Pin
#define LPF1_GPIO_Port   GPIOE
#define LPF1_Pin         GPIO_PIN_1
#define LPF2_GPIO_Port   GPIOE
#define LPF2_Pin         GPIO_PIN_2
#define LPF3_GPIO_Port   GPIOE
#define LPF3_Pin         GPIO_PIN_3
#define LPF4_GPIO_Port   GPIOE
#define LPF4_Pin         GPIO_PIN_4
#define LPF5_GPIO_Port   GPIOE
#define LPF5_Pin         GPIO_PIN_5
#define LPF6_GPIO_Port   GPIOC
#define LPF6_Pin         GPIO_PIN_14
#endif /* !LPF1_Pin */
