#define PTT_IN_ACTIVE_LOW  1

/* PTT_OUT (PC15): keying feedback back to the radio, ACTIVE HIGH.
 * Driven high once the amplifier is actually passing RF, i.e. after the
 * 15 ms break-before-make delay has closed RELAY1.  Dropped immediately
 * (no delay) whenever the state machine leaves PTT_STATE_TX_RUNNING or
 * protection trips. */
